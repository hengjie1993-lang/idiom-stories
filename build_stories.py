def main():
    out = []
    seen = set()
    for word, pinyin, story, source, quote, moral in DATA:
        if word in seen:
            continue
        seen.add(word)
        out.append(
            {
                "id": len(out) + 1,
                "word": word,
                "pinyin": pinyin,
                "story": story.strip(),
                "source": source,
                "quote": quote,
                "moral": moral,
            }
        )
    path = os.path.join(ROOT, "stories.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)

    print(f"wrote {len(out)} stories -> {path}")
    lens = [len(s["story"].replace("\n", "").replace(" ", "")) for s in out]
    print(f"故事字数: 最短 {min(lens)} | 最长 {max(lens)} | 平均 {sum(lens) // len(lens)}")
    for s in out:
        n = len(s["story"].replace("\n", "").replace(" ", ""))
        flag = "" if 300 <= n <= 460 else "  <-- 超出目标区间"
        print(f"  {s['id']:>2}. {s['word']}  {n} 字{flag}")


if __name__ == "__main__":
    main()
