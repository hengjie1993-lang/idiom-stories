def auto_tags(e):
    # 仅在「成语本身」四字内匹配，避免正文高频字（一/心/言/学…）造成过噪
    text = e['word']
    tags = []
    for th, kws in KEYWORDS.items():
        for kw in kws:
            if kw in text:
                tags.append(th)
                break
    # 低频多字短语：正文/出处/原文精确匹配，扩覆盖
    story = e.get('story','') + e.get('source','') + e.get('quote','')
    for th, phs in STORY_PHRASES.items():
        for ph in phs:
            if ph in story:
                if th not in tags:
                    tags.append(th)
                break
    # 优先级去重保序
    seen = set(); out = []
    for t in tags:
        if t not in seen:
            seen.add(t); out.append(t)
    return out

def main():
    d = json.load(open(SRC, encoding='utf-8'))
    if os.path.exists(BAK):
        print('备份已存在，跳过备份：', BAK)
    else:
        shutil.copy(SRC, BAK)
        print('已备份原文件 ->', BAK)
    curated_set = set(CURATED.keys())
    for e in d:
        w = e['word']
        if w in CURATED:
            e['tags'] = CURATED[w]
        else:
            t = auto_tags(e)
            e['tags'] = t if t else ['其他']
    json.dump(d, open(SRC, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    # 统计
    cnt = collections.Counter()
    for e in d:
        for t in e['tags']:
            cnt[t] += 1
    print('总条数:', len(d))
    print('主题分布:')
    for th in THEMES:
        print('  %-4s %4d' % (th, cnt.get(th,0)))
    print('  其他 %4d' % cnt.get('其他',0))
    # 抽几条自动打标的看质量
    print('\n自动打标抽样（非校准）:')
    shown = 0
    for e in d:
        if e['word'] not in curated_set and e['tags'] != ['其他'] and shown < 12:
            print('  %s -> %s' % (e['word'], ' / '.join(e['tags'])))
            shown += 1
    print('\n校准命中:', sum(1 for e in d if e['word'] in curated_set), '条')

if __name__ == '__main__':
    main()
